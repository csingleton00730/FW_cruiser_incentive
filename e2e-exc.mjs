await page.waitForTimeout(600)
console.log('AFTER', (await ger.innerText()).replace(/\n/g, ' | '))
console.log('ELIGIBLE AFTER', await page.locator('.stat .v').nth(2).innerText())
console.log('ATTENTION', (await page.locator('.attention li').allInnerTexts()).filter(t => t.includes('Gerardo')))
