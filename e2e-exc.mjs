await page.screenshot({ path: OUT + 'exc-2-override.png', fullPage: false })
const btn = page.locator('.modal button', { hasText: 'against the manual' })
console.log('DISABLED w/o fields', await btn.isDisabled())
await page.locator('.modal label.field input').nth(0).fill('Center Manager wants him paid; 15 minutes short')
await page.locator('.modal label.field input').nth(1).fill('Chance Singleton')
console.log('DISABLED w/o ack', await btn.isDisabled(), '|', await page.locator('.modal .row.between .small').innerText())
await page.locator('.modal label.ack input').check()
console.log('ENABLED after ack', !(await btn.isDisabled()))
await page.screenshot({ path: OUT + 'exc-3-ready.png' })
